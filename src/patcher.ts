// ── Patch type ───────────────────────────────────────────────────

export interface Patch {
  /** Human-readable name for diagnostics. */
  name: string;
  /** String to search for in the file content. */
  search: string;
  /** Replacement string. */
  replace: string;
}

export interface PatchResult {
  /** The patched content. */
  content: string;
  /** Names of patches that were applied. */
  applied: string[];
  /** Names of patches whose search string was not found. */
  missed: string[];
}

/**
 * Apply a list of patches to file content.
 * Returns the result with lists of applied and missed patches.
 */
export function applyPatches(content: string, patches: Patch[]): PatchResult {
  let result = content;
  const applied: string[] = [];
  const missed: string[] = [];

  for (const patch of patches) {
    if (result.includes(patch.search)) {
      result = result.replace(patch.search, patch.replace);
      applied.push(patch.name);
    } else {
      missed.push(patch.name);
    }
  }

  return { content: result, applied, missed };
}

